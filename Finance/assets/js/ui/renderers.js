        function buildDebtAndLentAggregates(transactions) {
            const debtPaidByCategory = Object.create(null);
            const debtBorrowedByCategory = Object.create(null);
            const debtPaidByUnlinkedCategory = Object.create(null);
            const debtBorrowedByUnlinkedCategory = Object.create(null);
            const debtPaidById = Object.create(null);
            const debtBorrowedById = Object.create(null);
            const lentExpensesByCategory = Object.create(null);
            const lentIncomeByCategory = Object.create(null);
            const lentExpensesByUnlinkedCategory = Object.create(null);
            const lentIncomeByUnlinkedCategory = Object.create(null);
            const lentExpensesById = Object.create(null);
            const lentIncomeById = Object.create(null);

            (transactions || []).forEach(t => {
                const category = (t && typeof t.category === 'string') ? t.category : '';
                if (!category) return;

                const amt = Number(t.amt) || 0;
                if (amt <= 0) return;

                const debtId = String(t.debtId || '').trim();
                if (t.type === 'expense') {
                    debtPaidByCategory[category] = (debtPaidByCategory[category] || 0) + amt;
                    if (debtId) {
                        debtPaidById[debtId] = (debtPaidById[debtId] || 0) + amt;
                    } else {
                        debtPaidByUnlinkedCategory[category] = (debtPaidByUnlinkedCategory[category] || 0) + amt;
                    }
                    if (category.startsWith('Lent: ')) {
                        lentExpensesByCategory[category] = (lentExpensesByCategory[category] || 0) + amt;
                        const lentId = String(t.lentId || '').trim();
                        if (lentId) {
                            lentExpensesById[lentId] = (lentExpensesById[lentId] || 0) + amt;
                        } else {
                            lentExpensesByUnlinkedCategory[category] = (lentExpensesByUnlinkedCategory[category] || 0) + amt;
                        }
                    }
                    return;
                }

                const debtBorrowDelta = typeof getDebtBorrowLiabilityDelta === 'function'
                    ? getDebtBorrowLiabilityDelta(t)
                    : 0;

                if (debtBorrowDelta > 0) {
                    debtBorrowedByCategory[category] = (debtBorrowedByCategory[category] || 0) + debtBorrowDelta;
                    if (debtId) {
                        debtBorrowedById[debtId] = (debtBorrowedById[debtId] || 0) + debtBorrowDelta;
                    } else {
                        debtBorrowedByUnlinkedCategory[category] = (debtBorrowedByUnlinkedCategory[category] || 0) + debtBorrowDelta;
                    }
                }

                const isLentRepaymentCashIn = category.startsWith('Lent: ')
                    && (t.type === 'income' || (typeof isNonIncomeCashInTx === 'function' && isNonIncomeCashInTx(t)));
                if (isLentRepaymentCashIn) {
                    lentIncomeByCategory[category] = (lentIncomeByCategory[category] || 0) + amt;
                    const lentId = String(t.lentId || '').trim();
                    if (lentId) {
                        lentIncomeById[lentId] = (lentIncomeById[lentId] || 0) + amt;
                    } else {
                        lentIncomeByUnlinkedCategory[category] = (lentIncomeByUnlinkedCategory[category] || 0) + amt;
                    }
                }
            });

            return {
                debtPaidByCategory,
                debtBorrowedByCategory,
                debtPaidByUnlinkedCategory,
                debtBorrowedByUnlinkedCategory,
                debtPaidById,
                debtBorrowedById,
                lentExpensesByCategory,
                lentIncomeByCategory,
                lentExpensesByUnlinkedCategory,
                lentIncomeByUnlinkedCategory,
                lentExpensesById,
                lentIncomeById
            };
        }

        function normalizeDebtNameKey(name) {
            return String(name || '').trim().toLowerCase();
        }

        function buildDebtCategoryFallbackOwners(debts = []) {
            const owners = Object.create(null);
            (debts || []).forEach(debt => {
                const debtId = String(debt?.id || '').trim();
                const names = typeof getDebtCategoryMatchNames === 'function'
                    ? getDebtCategoryMatchNames(debt)
                    : [String(debt?.name || '').trim()].filter(Boolean);

                names.forEach(name => {
                    const key = normalizeDebtNameKey(name);
                    if (!key || owners[key]) return;
                    owners[key] = debtId;
                });
            });
            return owners;
        }

        function canUseDebtCategoryFallback(debt, fallbackOwners = null) {
            const debtId = String(debt?.id || '').trim();
            const names = typeof getDebtCategoryMatchNames === 'function'
                ? getDebtCategoryMatchNames(debt)
                : [String(debt?.name || '').trim()].filter(Boolean);
            if (!names.length) return false;
            if (!fallbackOwners) return true;
            return names.some(name => {
                const key = normalizeDebtNameKey(name);
                return !fallbackOwners[key] || fallbackOwners[key] === debtId;
            });
        }

        function getDebtAggregateAmounts(debt, aggregates = {}, fallbackOwners = null) {
            const debtId = String(debt?.id || '').trim();
            const debtName = String(debt?.name || '').trim();
            const debtCategories = typeof getDebtCategoryMatchNames === 'function'
                ? getDebtCategoryMatchNames(debt)
                : [debtName].filter(Boolean);
            const useCategoryFallback = canUseDebtCategoryFallback(debt, fallbackOwners);
            const paidById = debtId ? Number(aggregates.debtPaidById?.[debtId] || 0) : 0;
            const borrowedById = debtId ? Number(aggregates.debtBorrowedById?.[debtId] || 0) : 0;
            const paidCategorySource = aggregates.debtPaidByUnlinkedCategory || aggregates.debtPaidByCategory || {};
            const borrowedCategorySource = aggregates.debtBorrowedByUnlinkedCategory || aggregates.debtBorrowedByCategory || {};
            const paidByCategory = useCategoryFallback
                ? debtCategories.reduce((sum, category) => sum + Number(paidCategorySource[category] || 0), 0)
                : 0;
            const borrowedByCategory = useCategoryFallback
                ? debtCategories.reduce((sum, category) => sum + Number(borrowedCategorySource[category] || 0), 0)
                : 0;

            return {
                paid: paidById + paidByCategory,
                borrowedMore: borrowedById + borrowedByCategory
            };
        }

