        function getRecentMovementFeatureLockInfo(tx) {
            if (!tx || typeof tx !== 'object') return null;

            const autoSource = String(tx.autoGeneratedSource || '').trim().toLowerCase();
            if (
                autoSource === 'crypto_buy' ||
                autoSource === 'crypto_sell' ||
                (typeof isAutoCryptoBuyExpenseTx === 'function' && isAutoCryptoBuyExpenseTx(tx)) ||
                (typeof isAutoCryptoSellProceedsTx === 'function' && isAutoCryptoSellProceedsTx(tx)) ||
                String(tx.linkedCryptoTransactionId || '').trim()
            ) {
                return {
                    feature: 'Crypto Portfolio',
                    message: 'This movement is auto-created from the Crypto Portfolio. Edit or delete the source crypto transaction there instead.'
                };
            }

            if (String(tx.linkedBillId || '').trim() || String(tx.linkedBillCycleId || '').trim()) {
                return {
                    feature: 'Bills',
                    message: 'This movement is linked to a bill payment record. Edit or delete the bill payment from the Bills card instead.'
                };
            }

            if (tx.type === 'credit_card_payment') {
                return {
                    feature: 'Credit Cards',
                    message: 'This movement is a credit card payment record. Manage it from the Credit Cards card instead.'
                };
            }

            if (tx.type === 'installment_payment' || String(tx.installmentPlanId || '').trim()) {
                return {
                    feature: 'BNPL / Installments',
                    message: 'This movement is linked to a BNPL or installment plan. Manage it from the BNPL/Installments card instead.'
                };
            }

            if (tx.type === 'debt_increase' || String(tx.debtId || '').trim()) {
                return {
                    feature: 'Debts to Pay',
                    message: 'This movement is linked to debt activity. Manage it from the Debts to Pay card instead.'
                };
            }

            return null;
        }

