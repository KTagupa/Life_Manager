test('Statement UI and storage preserve projection provenance and new cash-flow fields', () => {
    const financeRoot = path.join(__dirname, '..');
    const ui = fs.readFileSync(path.join(financeRoot, 'assets/js/features/statements.js'), 'utf8');
    const storage = fs.readFileSync(path.join(financeRoot, 'assets/js/core/storage.js'), 'utf8');

    assert.match(ui, /statementProjectionSchemaVersion/);
    assert.match(ui, /statementProvenance/);
    assert.match(ui, /Finance Costs/);
    assert.match(ui, /Card Purchases \(Non-cash\)/);
    assert.match(ui, /finance:metric-shadow-updated/);
    assert.match(storage, /normalizeStoredStatementProvenance/);
    assert.match(storage, /financeCosts/);
    assert.match(storage, /transferCashFlow/);
    assert.match(storage, /installmentPayments/);
});
